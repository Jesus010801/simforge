class TestAssembleScriptUsesItp:
    def test_no_pdb2gmx_on_lipids_only_gro(self, workspace):
        """run_assemble_system.py must NOT call pdb2gmx -f lipids_only.gro."""
        assemble_dir = _step_dir(workspace, "assemble_system_topology")
        script = (assemble_dir / "run_assemble_system.py").read_text()
        assert "lipids_only.gro" not in script or "pdb2gmx" not in script, (
            "run_assemble_system.py must not call pdb2gmx with lipids_only.gro"
        )
        # Stronger: if pdb2gmx appears, it must not be near lipids_only
        if "pdb2gmx" in script and "lipids_only.gro" in script:
            pdb2gmx_lines = [l for l in script.splitlines() if "pdb2gmx" in l or "lipids_only" in l]
            pytest.fail(
                "pdb2gmx and lipids_only.gro both appear in run_assemble_system.py:\n"
                + "\n".join(pdb2gmx_lines)
            )

    def test_script_has_lipid_itp_map(self, workspace):
        """run_assemble_system.py must contain _LIPID_ITP_MAP mapping DPP to dpp.itp."""
        assemble_dir = _step_dir(workspace, "assemble_system_topology")
        script = (assemble_dir / "run_assemble_system.py").read_text()
        assert "_LIPID_ITP_MAP" in script, (
            "run_assemble_system.py must define _LIPID_ITP_MAP for static ITP lookup"
        )
        assert "dpp.itp" in script, (
            "run_assemble_system.py must reference dpp.itp in _LIPID_ITP_MAP"
        )

    def test_script_references_itp_include(self, workspace):
        """run_assemble_system.py must build #include 'dpp.itp' rather than calling pdb2gmx."""
        assemble_dir = _step_dir(workspace, "assemble_system_topology")
        script = (assemble_dir / "run_assemble_system.py").read_text()
        assert "_lip_itp_path" in script or "_lip_itp_parts" in script, (
            "run_assemble_system.py must look up lipid ITP path from ASSETS_DIR"
        )

    def test_script_has_bootstrap_moltype_check(self, workspace):
        """run_assemble_system.py must run moleculetype validation before bootstrap sys.exit(0)."""
        assemble_dir = _step_dir(workspace, "assemble_system_topology")
        script = (assemble_dir / "run_assemble_system.py").read_text()
        assert "TOPOLOGY_ASSEMBLY_ERROR" in script or "Bootstrap moleculetype check" in script, (
            "run_assemble_system.py must validate moleculetypes in bootstrap mode "
            "(not silently skip the check)"
        )
        assert "_check_moltype_consistency" in script or "_collect_moleculetypes" in script, (
            "run_assemble_system.py must define a moleculetype consistency checker"
        )


