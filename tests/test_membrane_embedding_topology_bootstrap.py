@pytest.fixture(scope="module")
def workspace(tmp_path_factory):
    """Build a membrane pipeline workspace; return the root path."""
    import os
    from core.compiler import SimulationCompiler
    from builders.workspace_builder import WorkspaceBuilder

    cfg_path = Path(__file__).resolve().parent.parent / "configs" / "membrane_orient_test.yaml"
    if not cfg_path.exists():
        pytest.skip(f"Test config not found: {cfg_path}")

    root = tmp_path_factory.mktemp("bootstrap_topology")
    orig_cwd = os.getcwd()
    os.chdir(cfg_path.parent)
    try:
        result = SimulationCompiler().compile(str(cfg_path))
    finally:
        os.chdir(orig_cwd)
    WorkspaceBuilder().build(result, workspace_path=root)
    return root


def _step_dir(workspace: Path, step_id: str) -> Path:
    matches = [d for d in (workspace / "steps").iterdir() if step_id in d.name]
    assert matches, f"Step '{step_id}' not found in {workspace / 'steps'}"
    return matches[0]


