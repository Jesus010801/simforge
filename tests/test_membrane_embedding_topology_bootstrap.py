class TestBootstrapMoltypeValidation:
    """Test the moleculetype consistency checker embedded in run_assemble_system.py."""

    def test_bootstrap_script_contains_error_message(self, workspace):
        """run_assemble_system.py must contain TOPOLOGY_ASSEMBLY_ERROR string."""
        assemble_dir = _step_dir(workspace, "assemble_system_topology")
        script = (assemble_dir / "run_assemble_system.py").read_text()
        assert "TOPOLOGY_ASSEMBLY_ERROR" in script, (
            "run_assemble_system.py must emit TOPOLOGY_ASSEMBLY_ERROR when a moleculetype "
            "is in [ molecules ] but not defined (caught before grompp runs)"
        )

    def test_moltype_checker_inline(self, tmp_path):
        """The _collect_moleculetypes logic catches undefined moleculetypes."""
        # Write a minimal topology with DPP in [ molecules ] but no definition
        top = tmp_path / "broken.top"
        top.write_text(
            "; no moleculetype definitions here\n"
            "\n"
            "[ system ]\nTest\n\n"
            "[ molecules ]\n"
            "DPP  100\n"
        )
        # Inline the same logic as in the generated script
        check_script = tmp_path / "check.py"
        check_script.write_text(
            "import re, sys\n"
            "from pathlib import Path\n"
            "\n"
            "def _collect_moleculetypes(f, visited=None):\n"
            "    if visited is None: visited = set()\n"
            "    key = str(Path(f).resolve())\n"
            "    if key in visited: return []\n"
            "    visited.add(key)\n"
            "    result = []\n"
            "    try: txt = Path(f).read_text()\n"
            "    except OSError: return result\n"
            "    _in_mt = False\n"
            "    for _l in txt.splitlines():\n"
            "        _ls = _l.lstrip()\n"
            "        if re.match(r'^\\[\\s*moleculetype\\s*\\]', _ls, re.IGNORECASE):\n"
            "            _in_mt = True; continue\n"
            "        if _in_mt:\n"
            "            if _ls and not _ls.startswith(';') and not _ls.startswith('['):\n"
            "                result.append(_ls.split()[0]); _in_mt = False\n"
            "            elif _ls.startswith('['):\n"
            "                _in_mt = False\n"
            "        if _ls.startswith('#include'):\n"
            "            _pts = _ls.split('\"')\n"
            "            if len(_pts) >= 2:\n"
            "                _cand = (Path(f).parent / _pts[1]).resolve()\n"
            "                if _cand.exists(): result += _collect_moleculetypes(str(_cand), visited)\n"
            "    return result\n"
            "\n"
            "top = Path(sys.argv[1])\n"
            "defined = set(_collect_moleculetypes(str(top)))\n"
            "txt = top.read_text()\n"
            "mol_m = re.search(r'^\\s*\\[\\s*molecules\\s*\\](.*)', txt,\n"
            "                  re.MULTILINE | re.IGNORECASE | re.DOTALL)\n"
            "mol_names = []\n"
            "if mol_m:\n"
            "    for mbl in mol_m.group(1).splitlines():\n"
            "        mbl = mbl.strip()\n"
            "        if mbl and not mbl.startswith(';') and not mbl.startswith('#'):\n"
            "            mbs = mbl.split()\n"
            "            if mbs: mol_names.append(mbs[0])\n"
            "undef = [n for n in mol_names if n not in defined]\n"
            "for u in undef:\n"
            "    print(f'TOPOLOGY_ASSEMBLY_ERROR: {u!r} undefined', file=sys.stderr)\n"
            "sys.exit(1 if undef else 0)\n"
        )

        ret = subprocess.run(
            [sys.executable, str(check_script), str(top)],
            capture_output=True,
            text=True,
        )
        assert ret.returncode == 1, "Check must exit 1 for missing moleculetype DPP"
        assert "DPP" in ret.stderr and "TOPOLOGY_ASSEMBLY_ERROR" in ret.stderr

