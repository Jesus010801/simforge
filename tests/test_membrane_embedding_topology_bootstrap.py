class TestDppItpAsset:
    def test_dpp_itp_exists(self):
        assert (_FF_DIR / "dpp.itp").exists(), (
            "docs/Prot-Memb_FILES/oplsaa_membrane.ff/dpp.itp must exist "
            "(generated by core/lipid_itp_builder.py)"
        )

    def test_dpp_itp_has_moleculetype(self):
        text = (_FF_DIR / "dpp.itp").read_text()
        assert re.search(r"^\[\s*moleculetype\s*\]", text, re.MULTILINE | re.IGNORECASE), (
            "dpp.itp must contain a [ moleculetype ] section"
        )

    def test_dpp_moleculetype_name(self):
        text = (_FF_DIR / "dpp.itp").read_text()
        lines = text.splitlines()
        in_mt = False
        for line in lines:
            stripped = line.strip()
            if re.match(r"^\[\s*moleculetype\s*\]", stripped, re.IGNORECASE):
                in_mt = True
                continue
            if in_mt:
                if stripped and not stripped.startswith(";"):
                    name = stripped.split()[0]
                    assert name == "DPP", f"DPP moleculetype name should be 'DPP', got {name!r}"
                    return
        pytest.fail("No moleculetype name found in dpp.itp")

    def test_dpp_itp_has_atoms(self):
        text = (_FF_DIR / "dpp.itp").read_text()
        assert re.search(r"^\[\s*atoms\s*\]", text, re.MULTILINE | re.IGNORECASE)
        atom_lines = [
            l for l in text.splitlines()
            if l.strip() and not l.strip().startswith(";") and not l.strip().startswith("[")
            and re.match(r"^\s*\d+", l)
        ]
        # Count only atom lines (6-column format)
        mt_passed = False
        atoms_passed = False
        in_atoms = False
        count = 0
        for line in text.splitlines():
            stripped = line.strip()
            if re.match(r"^\[\s*moleculetype\s*\]", stripped, re.IGNORECASE):
                mt_passed = True
            if re.match(r"^\[\s*atoms\s*\]", stripped, re.IGNORECASE) and mt_passed:
                in_atoms = True
                atoms_passed = True
                continue
            if in_atoms:
                if stripped.startswith("["):
                    break
                if stripped and not stripped.startswith(";"):
                    count += 1
        assert count == 50, f"DPP should have 50 atoms, found {count}"

    def test_dpp_itp_has_bonds(self):
        text = (_FF_DIR / "dpp.itp").read_text()
        assert re.search(r"^\[\s*bonds\s*\]", text, re.MULTILINE | re.IGNORECASE)

    def test_dpp_itp_has_pairs(self):
        text = (_FF_DIR / "dpp.itp").read_text()
        assert re.search(r"^\[\s*pairs\s*\]", text, re.MULTILINE | re.IGNORECASE)

    def test_dpp_itp_has_angles(self):
        text = (_FF_DIR / "dpp.itp").read_text()
        assert re.search(r"^\[\s*angles\s*\]", text, re.MULTILINE | re.IGNORECASE)

    def test_dpp_itp_has_proper_dihedrals(self):
        text = (_FF_DIR / "dpp.itp").read_text()
        # Should have at least one dihedrals section (proper)
        assert len(re.findall(r"^\[\s*dihedrals\s*\]", text, re.MULTILINE | re.IGNORECASE)) >= 2, (
            "dpp.itp must have at least 2 [ dihedrals ] sections "
            "(one proper func=3, one improper func=1)"
        )

    def test_dpp_zero_charge(self):
        text = (_FF_DIR / "dpp.itp").read_text()
        in_atoms = False
        mt_found = False
        charges = []
        for line in text.splitlines():
            stripped = line.strip()
            if re.match(r"^\[\s*moleculetype\s*\]", stripped, re.IGNORECASE):
                mt_found = True
            if re.match(r"^\[\s*atoms\s*\]", stripped, re.IGNORECASE) and mt_found:
                in_atoms = True
                continue
            if in_atoms:
                if stripped.startswith("["):
                    break
                if stripped and not stripped.startswith(";"):
                    parts = stripped.split()
                    if len(parts) >= 7:
                        try:
                            charges.append(float(parts[6]))
                        except ValueError:
                            pass
        total_charge = sum(charges)
        assert abs(total_charge) < 0.001, f"DPP total charge should be 0, got {total_charge:.6f}"

    def test_dpp_no_forcefield_include(self):
        """dpp.itp must NOT include forcefield.itp (it's already included by protein topology)."""
        text = (_FF_DIR / "dpp.itp").read_text()
        for line in text.splitlines():
            if "#include" in line and "forcefield" in line:
                pytest.fail(
                    f"dpp.itp must not include forcefield.itp — it will be included "
                    f"by the protein topology before dpp.itp is referenced. Line: {line!r}"
                )


