"""
tests/test_membrane_embedding_topology_bootstrap.py
────────────────────────────────────────────────────
Verify that:

1. dpp.itp exists in oplsaa_membrane.ff/ and has a valid [ moleculetype ] DPP.
2. After workspace build, dpp.itp is staged to membrane_assets/oplsaa_membrane.ff/.
3. The generated run_assemble_system.py includes dpp.itp instead of calling
   pdb2gmx on lipids_only.gro.
4. The generated run_assemble_system.py runs moleculetype validation in bootstrap
   mode and exits non-zero if DPP is in [ molecules ] without a moleculetype.
5. Bootstrap topology written by run_assemble_system.py includes dpp.itp.
6. LipidItpBuilder generates valid ITP content from RTP.
"""

