def _write_pdb2gmx_outputs_from_cmd(cmd: list) -> None:
    """Write minimal pdb2gmx output files by extracting paths from cmd args."""
    for flag, content in [("-o", _MINIMAL_PROTEIN_GRO), ("-p", _MINIMAL_TOPOL_TOP), ("-i", "; posre\n")]:
        try:
            idx = list(cmd).index(flag)
            Path(cmd[idx + 1]).write_text(content)
        except (ValueError, IndexError, OSError):
            pass


