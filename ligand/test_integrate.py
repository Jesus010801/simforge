class TestValidateSystem:
    def _write_fixtures(self, tmp_path) -> dict:
        """Write all necessary files for a valid system."""
        # protein.gro
        pg = tmp_path / "protein.gro"
        pg.write_text(_MINIMAL_PROTEIN_GRO)

        # ligand.gro
        lg = tmp_path / "ligand.gro"
        lg.write_text(_MINIMAL_LIGAND_GRO)

        # complex.gro
        cg = tmp_path / "complex.gro"
        merge_gro_files(pg, lg, cg)

        # ligand.itp (without atomtypes — as it appears in out_dir)
        lig_itp = tmp_path / "E20.itp"
        _, cleaned = extract_atomtypes_section(_LIGAND_ITP_WITH_ATOMTYPES)
        lig_itp.write_text(cleaned)

        # ligand_atomtypes.itp
        at_itp = tmp_path / "ligand_atomtypes.itp"
        block, _ = extract_atomtypes_section(_LIGAND_ITP_WITH_ATOMTYPES)
        at_itp.write_text(block)

        # topol.top
        top = generate_topol_top(
            out_dir=tmp_path,
            forcefield="oplsaa",
            water_model="spce",
            protein_itp_name="protein.itp",
            ligand_itp_name="E20.itp",
            ligand_atomtypes_itp_name="ligand_atomtypes.itp",
            protein_mol_name="Protein_chain_A",
            ligand_mol_name="E20",
        )

        return {
            "complex_gro": cg,
            "ligand_itp": lig_itp,
            "atomtypes_itp": at_itp,
            "topol_top": top,
        }

    def test_valid_system_no_errors(self, tmp_path):
        f = self._write_fixtures(tmp_path)
        errors = validate_system(
            out_dir=tmp_path,
            protein_mol_name="Protein_chain_A",
            ligand_mol_name="E20",
            ligand_itp_path=f["ligand_itp"],
            complex_gro_path=f["complex_gro"],
            topol_top_path=f["topol_top"],
            ligand_atomtypes_itp_path=f["atomtypes_itp"],
            run_grompp=False,
        )
        assert errors == []

    def test_mol_name_mismatch_raises_error(self, tmp_path):
        f = self._write_fixtures(tmp_path)
        errors = validate_system(
            out_dir=tmp_path,
            protein_mol_name="Protein_chain_A",
            ligand_mol_name="WRONG",  # intentional mismatch
            ligand_itp_path=f["ligand_itp"],
            complex_gro_path=f["complex_gro"],
            topol_top_path=f["topol_top"],
            ligand_atomtypes_itp_path=f["atomtypes_itp"],
            run_grompp=False,
        )
        assert any("mismatch" in e.lower() for e in errors)

    def test_missing_atomtypes_itp_raises_error(self, tmp_path):
        f = self._write_fixtures(tmp_path)
        f["atomtypes_itp"].unlink()
        errors = validate_system(
            out_dir=tmp_path,
            protein_mol_name="Protein_chain_A",
            ligand_mol_name="E20",
            ligand_itp_path=f["ligand_itp"],
            complex_gro_path=f["complex_gro"],
            topol_top_path=f["topol_top"],
            ligand_atomtypes_itp_path=f["atomtypes_itp"],
            run_grompp=False,
        )
        assert any("atomtypes" in e.lower() for e in errors)

    def test_atomtypes_before_ligand_itp_required(self, tmp_path):
        f = self._write_fixtures(tmp_path)
        # Write a topol.top with WRONG include order (ligand before atomtypes)
        bad_top = tmp_path / "topol.top"
        bad_top.write_text(
            '#include "oplsaa.ff/forcefield.itp"\n'
            '#include "E20.itp"\n'
            '#include "ligand_atomtypes.itp"\n'
            '#include "protein.itp"\n'
            "[ system ]\nComplex\n[ molecules ]\nProtein 1\nE20 1\n"
        )
        errors = validate_system(
            out_dir=tmp_path,
            protein_mol_name="Protein_chain_A",
            ligand_mol_name="E20",
            ligand_itp_path=f["ligand_itp"],
            complex_gro_path=f["complex_gro"],
            topol_top_path=bad_top,
            ligand_atomtypes_itp_path=f["atomtypes_itp"],
            run_grompp=False,
        )
        assert any("order" in e.lower() or "before" in e.lower() for e in errors)

    def test_wrong_atom_count_in_gro(self, tmp_path):
        f = self._write_fixtures(tmp_path)
        # Corrupt complex.gro by changing the atom count header to a wrong value.
        # The parser will raise when declared count != actual atom lines.
        lines = f["complex_gro"].read_text().splitlines()
        lines[1] = "   99"  # declared 99, actual 8 → parse_gro raises
        f["complex_gro"].write_text("\n".join(lines) + "\n")
