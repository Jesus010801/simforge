class TestExtractAtomtypesSection:
    def test_extracts_block_correctly(self):
        block, remaining = extract_atomtypes_section(_LIGAND_ITP_WITH_ATOMTYPES)
        assert "[ atomtypes ]" in block
        assert "opls_100" in block
        assert "opls_101" in block

    def test_remaining_has_no_atomtypes_section(self):
        _, remaining = extract_atomtypes_section(_LIGAND_ITP_WITH_ATOMTYPES)
        assert "[ atomtypes ]" not in remaining
        # Note: atom type names (opls_XXX) still appear in [ atoms ] — that is correct.

    def test_remaining_preserves_moleculetype(self):
        _, remaining = extract_atomtypes_section(_LIGAND_ITP_WITH_ATOMTYPES)
        assert "[ moleculetype ]" in remaining
        assert "E20" in remaining

    def test_remaining_preserves_bonds(self):
        _, remaining = extract_atomtypes_section(_LIGAND_ITP_WITH_ATOMTYPES)
        assert "[ bonds ]" in remaining

    def test_no_atomtypes_returns_empty_block_and_unchanged_text(self):
        itp = "[ moleculetype ]\nLIG 3\n[ atoms ]\n1 opls_100 1 LIG C1 1 0.0 12.0\n"
        block, remaining = extract_atomtypes_section(itp)
        assert block == ""
        assert remaining == itp

    def test_atomtypes_block_includes_header_line(self):
        block, _ = extract_atomtypes_section(_LIGAND_ITP_WITH_ATOMTYPES)
        assert block.strip().startswith("[ atomtypes ]")

    def test_round_trip_preserves_content(self):
        block, remaining = extract_atomtypes_section(_LIGAND_ITP_WITH_ATOMTYPES)
        reassembled = block + remaining
        # All original content must still be present (possibly reordered)
        for keyword in ["opls_100", "E20", "[ bonds ]"]:
            assert keyword in reassembled

    def test_atomtypes_only_file(self):
        text = "[ atomtypes ]\nopls_1 C 12.0 0.0 A 3.5E-01 2.8E-01\n"
        block, remaining = extract_atomtypes_section(text)
        assert "opls_1" in block
        assert "opls_1" not in remaining


