class TestGenerateTopolTop:
    def _gen(self, tmp_path, water_ions_block="", protein_molecules=None) -> Path:
        if protein_molecules is None:
            protein_molecules = [("Protein_chain_A", 1)]
        return generate_topol_top(
            out_dir=tmp_path,
            forcefield="oplsaa",
            water_model="spce",
            protein_itp_name="protein.itp",
            ligand_itp_name="E20.itp",
            ligand_atomtypes_itp_name="ligand_atomtypes.itp",
            protein_molecules=protein_molecules,
            ligand_mol_name="E20",
            water_ions_block=water_ions_block,
        )

    def test_creates_topol_top(self, tmp_path):
        p = self._gen(tmp_path)
        assert p.exists()
        assert p.name == "topol.top"

    def test_includes_forcefield_first(self, tmp_path):
        text = self._gen(tmp_path).read_text()
        ff_pos = text.index("forcefield.itp")
        at_pos = text.index("ligand_atomtypes.itp")
        assert ff_pos < at_pos

    def test_ligand_atomtypes_before_ligand_itp(self, tmp_path):
        text = self._gen(tmp_path).read_text()
        at_pos = text.index("ligand_atomtypes.itp")
        lig_pos = text.index("E20.itp")
        assert at_pos < lig_pos, "atomtypes must come before ligand itp"

    def test_protein_itp_before_ligand_itp(self, tmp_path):
        text = self._gen(tmp_path).read_text()
        prot_pos = text.index("protein.itp")
        lig_pos = text.index("E20.itp")
        assert prot_pos < lig_pos

    def test_molecules_section_contains_both(self, tmp_path):
        text = self._gen(tmp_path).read_text()
        assert "Protein_chain_A" in text
        assert "E20" in text

    def test_both_in_molecules_with_count_1(self, tmp_path):
        text = self._gen(tmp_path).read_text()
        assert "Protein_chain_A           1" in text
        assert "E20            1" in text

    def test_default_water_ions_block_has_spce(self, tmp_path):
        text = self._gen(tmp_path).read_text()
        assert "spce.itp" in text

    def test_default_water_ions_block_has_ions(self, tmp_path):
        text = self._gen(tmp_path).read_text()
        assert "ions.itp" in text

    def test_custom_water_ions_block_used_verbatim(self, tmp_path):
        custom = '#include "charmm36.ff/tip3p.itp"\n#include "charmm36.ff/ions.itp"'
        text = self._gen(tmp_path, water_ions_block=custom).read_text()
        assert "tip3p.itp" in text
        assert "charmm36.ff" in text

    def test_system_section_present(self, tmp_path):
        text = self._gen(tmp_path).read_text()
        assert "[ system ]" in text

    def test_molecules_section_after_ions(self, tmp_path):
        text = self._gen(tmp_path).read_text()
        ions_pos = text.index("ions.itp")
        mol_pos = text.index("[ molecules ]")
        assert ions_pos < mol_pos


