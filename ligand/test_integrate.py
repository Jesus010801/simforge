def _mock_obabel_success(cmd, *args, **kwargs):
    """side_effect for subprocess.run that simulates a successful obabel run."""
    # Extract the -O output path from the command
    try:
        o_idx = list(cmd).index("-O")
        out_file = Path(cmd[o_idx + 1])
    except (ValueError, IndexError):
        return MagicMock(returncode=0, stderr="")

    out_file.write_text(
        "HETATM    1  C1  E20 A 201      15.000  15.000  15.000  1.00  0.00           C\n"
        "HETATM    2  H1  E20 A 201      15.300  15.000  15.000  1.00  0.00           H\n"
        "END\n"
    )
    return MagicMock(returncode=0, stderr="")


def _mock_obabel_failure(cmd, *args, **kwargs):
    """side_effect for subprocess.run that simulates an obabel failure."""
    return MagicMock(returncode=1, stderr="Open Babel Error: could not read molecule")


